"""Regenerate src/biomysterybench/manifest.json from HuggingFace metadata.

    HF_TOKEN=hf_... uv run python scripts/make_manifest.py

The manifest records, for each problem at the pinned dataset revisions, the
archive that holds its data, the archive's size and LFS sha256, its size tier
and whether a human solved it. The task reads it to select tiers and to verify
every archive it downloads into a sandbox. It holds no problem text or rubric.

Run it again whenever FULL_REVISION or PREVIEW_REVISION changes. The full set
is gated, so HF_TOKEN needs access to it.
"""

import csv
import json
import os
import sys
from pathlib import Path

from huggingface_hub import HfApi, hf_hub_download

from biomysterybench.biomysterybench import (
    _YES,
    FULL_REPO,
    FULL_REVISION,
    PREVIEW_REPO,
    PREVIEW_REVISION,
)
from biomysterybench.manifest import MANIFEST_PATH, PREVIEW_ARCHIVE, TIER_BOUNDS


def tier_for(size: int) -> str:
    for name, upper in TIER_BOUNDS:
        if upper is None or size < upper:
            return name
    raise AssertionError("TIER_BOUNDS must end with an unbounded tier")


def source_entry(repo: str, revision: str, preview: bool, token: str | None) -> dict:
    api = HfApi()
    info = api.dataset_info(repo, revision=revision, files_metadata=True, token=token)
    if info.sha != revision:
        sys.exit(f"{repo}: asked for {revision}, HuggingFace returned {info.sha}")
    files = {s.rfilename: s for s in info.siblings or []}

    csv_path = hf_hub_download(
        repo, "problems.csv", repo_type="dataset", revision=revision, token=token
    )
    with open(csv_path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    problems = {}
    for row in rows:
        pid = row["id"]
        archive = PREVIEW_ARCHIVE if preview else f"data/{pid}.zip"
        sibling = files.get(archive)
        if sibling is None or sibling.lfs is None:
            sys.exit(f"{repo}@{revision}: no LFS archive {archive} for {pid}")
        problems[pid] = {
            "archive": archive,
            "size": sibling.lfs.size,
            "sha256": sibling.lfs.sha256,
            "tier": tier_for(sibling.lfs.size),
            "human_solvable": row["human_solvable"].strip().lower() in _YES,
        }
    return {"repo": repo, "revision": revision, "problems": problems}


def main() -> None:
    token = os.environ.get("HF_TOKEN") or None
    manifest = {
        "_comment": "Generated by scripts/make_manifest.py. Do not edit by hand.",
        "tier_bounds_bytes": dict(TIER_BOUNDS),
        "sources": {
            "full": source_entry(FULL_REPO, FULL_REVISION, False, token),
            "preview": source_entry(PREVIEW_REPO, PREVIEW_REVISION, True, token),
        },
    }
    MANIFEST_PATH.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    for name, src in manifest["sources"].items():
        problems = src["problems"].values()
        total = sum(p["size"] for p in problems)
        print(f"{name}: {len(src['problems'])} problems, {total / 1e9:.1f} GB")
    print(f"wrote {Path(MANIFEST_PATH).relative_to(Path.cwd())}")


if __name__ == "__main__":
    main()
